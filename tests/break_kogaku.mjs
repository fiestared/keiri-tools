// 本文だけを狙うため、<article> 以降に限定して置換する
const inBody = (html, a, b) => {
  const i = html.indexOf('<article>');
  const head = html.slice(0, i), body = html.slice(i);
  if (!body.includes(a)) throw new Error(`壊し方が外れている（本文に "${a.slice(0, 40)}" が無い）`);
  return head + body.replace(a, b);
};

// 同じ主張が本文の複数箇所に出るとき、1箇所だけ壊しても主張は残る（規則7の裏返し）。
// 「その主張を本当に消す」壊し方には全置換が要る。
const inBodyAll = (html, a, b) => {
  const i = html.indexOf('<article>');
  const head = html.slice(0, i), body = html.slice(i);
  if (!body.includes(a)) throw new Error(`壊し方が外れている（本文に "${a.slice(0, 40)}" が無い）`);
  return head + body.split(a).join(b);
};

