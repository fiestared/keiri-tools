#!/usr/bin/env python3
"""内容証明の料金と字数制限を、日本郵便の公表値で照合する（外部オラクル）。

記事に書く数字は自分の算数ではなく、日本郵便が別の場所で公表している合計値と
噛み合うことを確かめてから使う。噛み合えば読み違えていないと分かる。

出典（いずれも curl で生HTMLを取得。要約器は通していない）:
  https://www.post.japanpost.jp/service/fuka_service/syomei/use.html
  https://www.post.japanpost.jp/service/fuka_service/syomei/
  https://www.post.japanpost.jp/service/enaiyo/index.html
"""

ok = True


def check(label, got, want):
    global ok
    hit = got == want
    ok = ok and hit
    print(f"  [{'OK ' if hit else 'NG '}] {label}: 計算 {got} / 公表 {want}")


print("=== ① 内容証明の加算料金は 480円 + 290円×(枚数-1) か ===")
# 公表: 謄本1枚480円 / 2枚770 / 3枚1,060 / 4枚1,350 / 5枚1,640
#      本文「内容証明の加算料金は480円（2枚目以降は290円増）」
published = {1: 480, 2: 770, 3: 1060, 4: 1350, 5: 1640}
for n, want in published.items():
    check(f"謄本{n}枚", 480 + 290 * (n - 1), want)

print("\n=== ② 窓口で謄本1枚・定形を出したときの合計 ===")
# 公表の計算例: (内容証明)480 + (郵便物)110 + (一般書留)480 = 1,070円
check("内容証明480+定形110+書留480", 480 + 110 + 480, 1070)
# 配達証明(差し出しの際)350円を足した実務の標準形
print(f"  [--] 参考: 配達証明350円を足すと {480 + 110 + 480 + 350}円（公表の合計例は無い＝加算の明示から算出）")

print("\n=== ③ 横書きの3つの様式は、どれも1枚520字か ===")
# 公表: 縦書き 1行20字×26行 / 横書き 20×26・13×40・26×20
# 別ページの公表: 「郵便局の窓口で差し出す場合の内容証明文書の文字数は1枚当たり520文字です」
for cols, rows in [(20, 26), (13, 40), (26, 20)]:
    check(f"1行{cols}字×1枚{rows}行", cols * rows, 520)

print("\n=== ④ e内容証明の合計（1枚・通常送付） ===")
# 公表の内訳: 郵便物110 + 電子内容証明文書1枚目19 + 謄本1枚目382 + 通常送付304 + 一般書留480
check("110+19+382+304+480", 110 + 19 + 382 + 304 + 480, 1295)

print("\n=== ⑤ 公表の比較表（3枚・1,560字）と噛み合うか ===")
# 公表: 窓口 1,560文字=3枚 → 1,650円 ／ e内容証明 1枚(～1,584字) → 1,295円 ／ 差 355円お得
madoguchi_3mai = 480 + 290 * 2 + 110 + 480  # 内容証明3枚 + 定形 + 書留
check("窓口3枚の合計", madoguchi_3mai, 1650)
check("窓口3枚 − e内容証明1枚", madoguchi_3mai - 1295, 355)
check("1,560字は窓口で3枚になるか（520字/枚）", -(-1560 // 520), 3)

print("\n=== ⑥ 同文内容証明は2通目以降が半額か ===")
# 公表: 「同文内容証明については、1通は上記に定める額とし、その他は1通ごとにその半額となります」
check("謄本1枚・2通目以降の加算料金", 480 // 2, 240)

print()
print("すべて一致" if ok else "★不一致あり — 記事に書く前に読み直すこと")
raise SystemExit(0 if ok else 1)
