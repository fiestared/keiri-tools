#!/usr/bin/env python3
"""裁判所の公表資料からの引用を、取得した生の本文に全数当てる（2026-08-25 第4便）。

★申し送り1485: check_quotes.py の ④ は渡したコーパス（e-Gov）しか見ないので、
  出典系統が違う引用は必ず「コーパスに無い」と出る。そこを
  「出典が違うから当たらなくて当然」で閉じると、本当の非逐語が混ざっていても分からない。
  → 系統ごとにコーパスを作って当て直す。

コーパスの3系統:
  最高裁「債権執行（債務名義に基づく差押え）」HTML
  福井地裁「債権差押命令の申立てをされる方へ」PDF（平成28年1月付）
  高松地裁「債権差押命令の申立てをされる方へ」PDF
"""
import re
import sys

PAGES = [
    "/tmp/courts_saiken.txt",     # 最高裁 HTML から抽出したテキスト
    "/tmp/c_fukui.txt",           # 福井地裁 PDF
    "/tmp/c_takamatsu.txt",       # 高松地裁 PDF
]


def norm(s):
    """空白を落とし、全角の記号・数字を半角に寄せる。

    裁判所のPDFは全角カンマ（，）と全角数字（４分の１）を使い、HTMLは半角を使う。
    どちらで書き写しても同じ主張になるので、この違いだけは吸収したうえで
    「語そのものを変えていないか」を見る。
    """
    s = re.sub(r"\s+", "", s)
    z = "０１２３４５６７８９，．（）"
    h = "0123456789,.()"
    s = s.translate(str.maketrans(z, h))
    s = s.replace("，", ",").replace("、", "、")
    return s


corpus = "".join(norm(open(p, encoding="utf-8", errors="replace").read()) for p in PAGES)
print(f"コーパス {len(corpus):,}字（裁判所 {len(PAGES)}資料）\n")

# 記事が裁判所の公表資料を出典として名乗っている主張。
# 地の文に落としてあるものも含め、言い切っている箇所を全部並べる。
QUOTES = [
    # 最高裁
    "差押命令が第三債務者に送達されると、差押えの効力が生じます",
    "原則として相手方の給料の4分の1(月給で44万円を超える場合には、33万円を除いた金額)を差し押さえることができます",
    "陳述催告の申立ては、債権差押命令申立てと同時にしてください",
    "手数料（原則として4000円）及び郵便料",
    "ただし、給料の差押えの場合については、養育費などを請求する場合を除いて4週間となります",
    "仮執行宣言付支払督促",
    "仮執行宣言付少額訴訟判決",
    "第三債務者が供託をした場合は、裁判所が配当等を行うので、直接取り立てることはできません",
    "原則として、債務者の住所地を管轄する地方裁判所です",
    # 福井地裁
    "差押えが可能な部分は,一般的には毎月の給与から所得税,住民税,社会保険料を控除した残額の4分の1までで,養育費等の請求の場合には毎月の給与の2分の1までです",
    "催告をしたにもかかわらず第三債務者が陳述書を提出しないこともありますが,裁判所が再度の催告を実施することはありません",
    # 高松地裁
    "第三債務者が差押命令正本を受け取ったことを確認できたのち、債務者に",
    "振込による入金を希望するときには、債権者が振込手数料を負担することになります",
    "債権者は、差押債権額を超えて取り立てることはできません",
]

ok = True
for q in QUOTES:
    hit = norm(q) in corpus
    ok = ok and hit
    print(f"  [{'OK ' if hit else 'NG '}] {q}")

print()
print("★全一致" if ok else "★不一致あり — 逐語でないなら言い切りをやめる/書き換える")
sys.exit(0 if ok else 1)
