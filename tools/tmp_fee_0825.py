def teigaku(v):
    """別表第一 一の項（＝別表第二 一の項イ）: 訴え提起の手数料"""
    f = 0
    b = min(v, 1_000_000)
    f += -(-b // 100_000) * 1000
    if v > 1_000_000:
        b = min(v, 5_000_000) - 1_000_000
        f += -(-b // 200_000) * 1000
    if v > 5_000_000:
        b = min(v, 10_000_000) - 5_000_000
        f += -(-b // 500_000) * 2000
    if v > 10_000_000:
        b = min(v, 1_000_000_000) - 10_000_000
        f += -(-b // 1_000_000) * 3000
    return f


print("請求額        訴え提起(イ)   支督イ=1/2   支督計(書面+2700)  支督計(電子+2500)")
for v in [100_000, 300_000, 500_000, 600_000, 1_000_000, 2_000_000, 3_000_000, 5_000_000, 10_000_000]:
    t = teigaku(v)
    h = t // 2
    print(f"{v:>11,}   {t:>9,}   {h:>9,}   {h+2700:>13,}   {h+2500:>13,}")

print()
print("検算（外部オラクル: 裁判所が公表する手数料額早見表の値と一致すべき）")
for v, exp in [(1_000_000, 10000), (500_000, 5000), (3_000_000, 20000), (10_000_000, 50000), (600_000, 6000)]:
    got = teigaku(v)
    print(f"  訴額 {v:>10,} → {got:>7,}   期待 {exp:>7,}   {'OK' if got == exp else 'NG'}")
