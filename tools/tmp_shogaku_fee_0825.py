# 民事訴訟費用等に関する法律 別表第二 一の項イ の階段を実装する。
# 手で転記せず、裁判所公表の手数料額早見表の値を外部オラクルとして照合する。
def kaidan(v: int) -> int:
    """別表第二 一の項イ（＝別表第一 一の項と同一の階段）。訴訟の目的の価額 v 円 → 円"""
    total = 0
    bands = [
        (1_000_000,   100_000, 1_000),   # 100万円までの部分: 10万円までごとに1,000円
        (5_000_000,   200_000, 1_000),   # 100万超500万まで : 20万円までごとに1,000円
        (10_000_000,  500_000, 2_000),   # 500万超1000万まで: 50万円までごとに2,000円
        (1_000_000_000, 1_000_000, 3_000),
        (5_000_000_000, 5_000_000, 10_000),
        (float('inf'), 10_000_000, 10_000),
    ]
    lo = 0
    for hi, step, fee in bands:
        if v <= lo:
            break
        part = min(v, hi) - lo
        total += -(-part // step) * fee   # 「…までごとに」＝切り上げ
        lo = hi
    return total


# 外部オラクル: 裁判所が公表している手数料額早見表の5点
ORACLE = {500_000: 5_000, 600_000: 6_000, 1_000_000: 10_000,
          3_000_000: 20_000, 10_000_000: 50_000}
ng = 0
for v, expect in sorted(ORACLE.items()):
    got = kaidan(v)
    ok = (got == expect)
    ng += (not ok)
    print(("OK " if ok else "NG ") + "訴額 %10s円 → イ %7s円 (早見表 %s円)"
          % ("{:,}".format(v), "{:,}".format(got), "{:,}".format(expect)))
print("--- 照合 %s ---" % ("全一致" if ng == 0 else "%d件不一致" % ng))

print()
print("=== 少額訴訟の申立て手数料（別表第二 一の項 = イ+ロ）===")
for v in (100_000, 300_000, 500_000, 600_000):
    i = kaidan(v)
    print("訴額 %7s円: イ %6s + ロ 2,500(書面) = %6s円 ／ イ %6s + ロ 1,400(電子) = %6s円"
          % ("{:,}".format(v), "{:,}".format(i), "{:,}".format(i + 2500),
             "{:,}".format(i), "{:,}".format(i + 1400)))
print()
print("=== 被告が複数のとき（別表第二 一の項ロ ただし書: (被告数-1)×2,000円 加算）===")
for n in (1, 2, 3):
    add = (n - 1) * 2_000
    print("訴額60万円・被告%d人: 書面 %6s円 ／ 電子 %6s円"
          % (n, "{:,}".format(kaidan(600_000) + 2500 + add),
             "{:,}".format(kaidan(600_000) + 1400 + add)))
